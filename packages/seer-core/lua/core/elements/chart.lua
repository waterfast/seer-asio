--- name --> true，用来查"这个名字是不是真的属性"
---@type table<string, boolean>
local ELEMENT_INDEX = {}
for i = 1, #ELEMENTS do
  local e = ELEMENTS[i]
  if ELEMENT_INDEX[e.name] then
    error(("属性克制表里有重名的属性：%s"):format(e.name), 2)
  end
  ELEMENT_INDEX[e.name] = true
end

--- 全部单属性名，顺序同 `ELEMENTS`
---@type string[]
local ELEMENT_NAMES = {}
for i = 1, #ELEMENTS do ELEMENT_NAMES[i] = ELEMENTS[i].name end

-- 倍率的四个取值，写成常量是为了让下面的构建代码里没有魔法数字
local NEUTRAL, STRONG, WEAK, IMMUNE = 1, 2, 0.5, 0

--- CHART[攻击属性][防御属性] = 倍率。每个攻击属性都有一整行，
--- 26 个防御属性一个不缺（中性项是显式的 1）。
---@type table<string, table<string, number>>
local CHART = {}

--- 把某个列表里的属性全部标成 `value`。
--- 顺手挡住两类错数据：名字不存在、同一条关系被写成两个倍率。
---@param owner string @ 攻击属性名（只用于报错信息）
---@param row table<string, number> @ 正在构建的那一行
---@param field string @ 字段名，如 "strong"（只用于报错信息）
---@param list string[] @ 属性名列表
---@param value number @ 倍率
local function fill(owner, row, field, list, value)
  for i = 1, #list do
    local defend = list[i]
    if not ELEMENT_INDEX[defend] then
      error(("属性克制表：%s 的 %s 里写了不存在的属性 \"%s\""):format(owner, field, defend), 2)
    end
    local old = row[defend]
    if old ~= nil and old ~= value then
      error(("属性克制表自相矛盾：%s 打 %s 既算 %s 倍又算 %s 倍"):format(owner, defend, old, value), 2)
    end
    row[defend] = value
  end
end

for i = 1, #ELEMENTS do
  local e = ELEMENTS[i]
  local row = {}
  fill(e.name, row, "strong", e.strong, STRONG)
  fill(e.name, row, "weak", e.weak, WEAK)
  fill(e.name, row, "immune", e.immune, IMMUNE)
  -- 剩下没被上面三条碰到的就是中性，显式写 1
  for j = 1, #ELEMENT_NAMES do
    local defend = ELEMENT_NAMES[j]
    if row[defend] == nil then row[defend] = NEUTRAL end
  end
  CHART[e.name] = row
end

return {
  CHART = CHART,
  ELEMENTS = ELEMENTS,
  ELEMENT_NAMES = ELEMENT_NAMES,
}
