-- ============================ 属性克制表（数据） ============================
--
-- 赛尔号的**精灵**有 1~2 个属性（元素），**技能**有 1 个属性。伤害里的属性倍率
-- 只看"技能的属性"对"受击精灵的属性"这一层关系，跟谁放的技能、技能是物理还是
-- 特殊都无关：
--
--     属性倍率 = CHART[技能属性][受击精灵属性]
--
-- 单属性对单属性只有 4 种倍率，本文件**照抄来源**，不做任何推导：
--
--     2    克制    —— 写在该攻击属性的 `strong` 列表里
--     0.5  微弱    —— 写在该攻击属性的 `weak` 列表里（被对方抵抗）
--     0    无效    —— 写在该攻击属性的 `immune` 列表里（对方免疫）
--     1    中性    —— 不在上面三个列表里的一律是 1
--
-- ---------------------------- 字段名为什么是英文 ----------------------------
--
-- 想用的字段名是 `克制` / `被克制` / `免疫`，但 **Lua 的标识符只能是 ASCII**
-- （`[A-Za-z_][A-Za-z0-9_]*`），`{ 克制 = ... }` 直接是语法错误，
-- 中文 key 只能写成 `{ ["克制"] = ... }`，取值也就只能 `e["克制"]`，读起来不如
-- `e.strong` 顺。所以字段名用英文，含义一一对应、在下面这张表里写死：
--
--     strong  ==  克制     该属性**打这些属性**是 2 倍
--     weak    ==  被克制   该属性**打这些属性**是 0.5 倍（即被对方抵抗）
--     immune  ==  免疫     该属性**打这些属性**是 0 倍（即对方免疫）
--
-- ---------------------------- `weak` 的方向 ----------------------------
--
-- 名字是按**攻击方**写的，别看反：
--
--     { name = "火", weak = { "水" } }   读作"火打水是 0.5 倍"
--
-- 也就是"火属性被水属性抵抗"。它**不是**"火被谁克制"——那要去查对方那条的
-- `strong` 里有没有"火"。一条数据只描述"我打出去"这一个方向，反方向的关系
-- 写在对方那条里；这也正是下一节那个自洽性检查能成立的原因。
--
-- ---------------------------- 矩阵 ----------------------------
--
-- `CHART` 是加载时由下面的 `ELEMENTS` 构建出来的：
--
--     CHART["电"]["水"]     == 2
--     CHART["电"]["地面"]   == 0
--     CHART["普通"]["草"]   == 1
--
-- 中性项**显式写成 1**（不是留 nil）：只要属性名合法，`CHART[a][b]` 就一定拿得到
-- 数字，调用方不用写 `or 1` 兜底——少一处兜底就少一处"忘了兜底"的 bug。
-- 名字不合法时 `CHART[a]` 是 nil，由 init.lua 负责报错。
--
-- 构建时还会做两件校验，都是**直接 error**：数据是静态的，写错了应该当场炸，
-- 而不是等某场对局里伤害莫名其妙（不会报错的那种 bug 最难查）：
--
--   1. 任何被引用到的属性名必须真实存在（挡住 `"雷"` 这种手滑）；
--   2. 同一个"攻击属性 → 防御属性"不允许被写出两个不同的倍率。
--
-- ---------------------------- 数据来源与可靠性 ----------------------------
--
-- 主来源：**赛尔号 WIKI（bilibili 游戏 wiki）的 `Module:属性克制`**。那不是一份
-- 抄来抄去的攻略文章，而是该站每个属性/精灵页面「属性克制」章节真正在用的数据表：
--
--     https://wiki.biligame.com/seer/index.php?title=Module:属性克制&action=raw
--
-- 抓取时（写下这份文件的那天）该表的状态：
--
--   * 26 个单属性 × 26 个单属性 = 676 条**全部有值**，没有空洞；
--   * 取值只有 { 2, 1, 0.5, 0 } 四种，和上面的倍率约定完全对得上；
--   * 该表同时存了"攻击表"和"防御表"两半，按定义防御表应当等于攻击表的转置。
--     逐条比对 676 组，只有 **1 条对不上**（圣灵 → 邪灵，见下）。这条自洽性检查
--     是敢拿它当主来源的主要依据。
--
-- 交叉核对（两个独立的第二来源，都是逐格比对，不是抽查）：
--
--   * **seer.fandom 中文 wiki** 的「属性相克表」词条（`api.php` 取的 wikitext）：
--     https://seer.fandom.com/zh/api.php?action=parse&page=属性相克表&prop=wikitext
--     完整 26×26 矩阵，和本表 **676 格里 674 格一致（99.7%）**；
--   * **4399 赛尔号「双属性相克表」**：
--     https://news.4399.com/seer/ssxxk/
--     逐格比对：单属性部分凡是它收录的都和本表一致，不一致的全部集中在
--     神灵 / 轮回 / 虫 / 虚空 这四个**它这一版还没收录**的新属性上（它不列 = 中性）。
--     它的「单属性打双属性」一栏有 1012/1021 格和本表的合并结果一致。
--
-- 三个来源两两对不上的格子一共 **4 条**，全部按项目规矩"不猜"——降级成中性 1，
-- 并在对应属性那条数据上留了 `-- TODO: 与图鉴核对`：
--
--     圣灵 打 邪灵   biligame 攻击表 0.5／防御表 1，fandom 1，4399 未列(1)     → 1
--     战斗 打 邪灵   biligame 两半 1，fandom 0.5，4399 未列(1)                → 1
--     轮回 打 虚空   biligame 两半 1，fandom 0.5，4399 攻击表 1／防御表 0.5   → 1
--     轮回 打 虫     biligame 两半 1，fandom 1，4399 攻击表 0／防御表未列(1)  → 1
--
-- 也就是说：676 条关系里 672 条三来源一致、直接采用，另外 4 条按中性 1 处理。
-- （4399 那两格里它自己的攻击表和防御表就互相打架，所以不能只看它。）
--
-- ---------------------------- 别把宝可梦的表抄进来 ----------------------------
--
-- 网上搜"属性克制表"出来的一大半是**宝可梦**的：钢、岩石、幽灵、恶、妖精、格斗
-- 这些属性赛尔号根本没有；"火克草冰虫钢"那种四连也是宝可梦的写法。本文件的
-- 26 个属性名全部来自上面的赛尔号来源，并且和 `lua/specs/` 里已经在用的写法
-- 一致（`{ "草" }`、`{ "电" }`、`{ "战斗" }`、`{ "水", "飞行" }`）。

